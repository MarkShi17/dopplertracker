def measurement_scene(seed=0, scenario="fast_chirp", sample_rate=SAMPLE_RATE, duration=DURATION_SECONDS):
    """Development scenes for Doppler-measurement precision (``audio_scene`` scenes are unchanged).

    A separate random stream, ``default_rng([seed, 2026])``.  Every pass carries
    harmonics 1-3 (amplitudes 0.26, 0.10, 0.06); events declare two harmonics.

    fast_chirp: two close passes (closest approach ~0.72 and ~0.86 km, sweeping
    up to ~3-4 Hz/s at the fundamental) and one distant pass; Gaussian noise 0.12
    and hum at 60, 120 and 180 Hz, where 120 Hz crosses the first pass.
    low_snr_audio: the ``audio_scene`` geometry with Gaussian noise 3.0, about
    13 dB per 0.25 Hz bin for the fundamental at closest approach and 5 dB for
    the second harmonic.
    hum_crossing (``HUM_SCENARIOS``): the ``audio_scene`` geometry with Gaussian
    noise 0.12, 60 Hz hum, and per pass three stationary lines at the received
    fundamental 6 s before, at and 5 s after closest approach plus one at the
    second harmonic 2 s after it (amplitude 0.06 each, slowly modulated by up to
    25 %, frequency drifting by up to 0.02 Hz over the scene), so that the tone
    crosses lines right where it sweeps fastest.
    """
    if scenario not in MEASUREMENT_SCENARIOS + HUM_SCENARIOS or sample_rate <= 0 or duration < 30:
        raise ValueError("invalid measurement scenario, sample rate, or duration")
    rng = np.random.default_rng([seed, 2026])
    sample_count = int(round(sample_rate * duration))
    receive = np.arange(sample_count, dtype=float) / sample_rate
    nominal = np.array([135.0, -85.0, 0.0])
    truth = nominal + np.r_[rng.uniform(-35, 35, 2), 0.0]
    if scenario == "fast_chirp":
        geometries = [
            ([85.0, 0.0, 0.0], (nominal + [0.0, 400.0, 600.0]).tolist(), 105.0, 111.0),
            ([0.0, 95.0, 0.0], (nominal + [-500.0, 0.0, 700.0]).tolist(), 300.0, 127.0),
            ([67.0, -55.0, 0.0], [1100.0, 1100.0, 850.0], 495.0, 103.0),
        ]
        noise, hums = 0.12, ((60.0, 0.08), (120.0, 0.06), (180.0, 0.036))
    elif scenario == "hum_crossing":
        geometries = [
            ([82.0, 0.0, 0.0], [0.0, 1700.0, 1000.0], 105.0, 111.0),
            ([0.0, 94.0, 0.0], [-1900.0, 0.0, 1300.0], 300.0, 127.0),
            ([67.0, -55.0, 0.0], [1100.0, 1100.0, 850.0], 495.0, 103.0),
        ]
        noise, hums = 0.12, ((60.0, 0.08),)
    else:
        geometries = [
            ([82.0, 0.0, 0.0], [0.0, 1700.0, 1000.0], 105.0, 111.0),
            ([0.0, 94.0, 0.0], [-1900.0, 0.0, 1300.0], 300.0, 127.0),
            ([67.0, -55.0, 0.0], [1100.0, 1100.0, 850.0], 495.0, 103.0),
        ]
        noise, hums = 3.0, ((60.0, 0.08), (180.0, 0.036))
    waveform = np.zeros(sample_count, dtype=np.float64)
    tracks, events, observed = [], [], []
    for i, (velocity, origin, center, f0) in enumerate(geometries):
        frequency, emission, heard_cpa, distance = analytic_pass(
            receive, velocity, origin, center, truth, f0, 343.0
        )
        track_times = np.arange(center - 145, center + 146, 2.0)
        track = Trajectory(
            f"measure-flight-{i}",
            track_times,
            np.asarray(origin) + (track_times - center)[:, None] * velocity,
        )
        visible = (emission >= track_times[0]) & (emission <= track_times[-1])
        phase = 2 * np.pi * np.cumsum(np.where(visible, frequency, 0.0)) / sample_rate
        fade = visible.astype(float) * np.exp(-0.5 * ((receive - heard_cpa) / 85.0) ** 2)
        for harmonic, amplitude in ((1, 0.26), (2, 0.10), (3, 0.06)):
            waveform += amplitude * fade * np.sin(harmonic * phase + rng.uniform(0, 2 * np.pi))
        tracks.append(track)
        events.append(
            Event(
                (heard_cpa - 55, heard_cpa + 55),
                heard_cpa,
                f0 + rng.normal(0, 0.12),
                float(np.linalg.norm(velocity)),
                distance,
                2,
            )
        )
        observed.append(frequency)
    for hz, amplitude in hums:
        waveform += amplitude * np.sin(2 * np.pi * hz * receive + rng.uniform(0, 2 * np.pi))
    crossing = []
    if scenario == "hum_crossing":
        for event, frequency in zip(events, observed, strict=True):
            for harmonic, delay in ((1, -6.0), (1, 0.0), (1, 5.0), (2, 2.0)):
                index = min(int(round((event.cpa + delay) * sample_rate)), sample_count - 1)
                crossing.append(harmonic * float(frequency[index]))
        for hz in crossing:
            drift = rng.uniform(-0.02, 0.02) / duration
            modulation = 1 + rng.uniform(0.1, 0.25) * np.sin(
                2 * np.pi * receive / rng.uniform(60.0, 240.0) + rng.uniform(0, 2 * np.pi)
            )
            phase = 2 * np.pi * (hz * receive + 0.5 * drift * receive**2) + rng.uniform(0, 2 * np.pi)
            waveform += 0.06 * modulation * np.sin(phase)
    waveform += rng.normal(0, noise, sample_count)
    return {
        "waveform": waveform.astype(np.float32),
        "sample_rate": sample_rate,
        "clock": 0.0,
        "truth": truth,
        "tracks": tracks,
        "events": events,
        "observed_frequency_hz": observed,
        "scenario": scenario,
        "seed": seed,
        "noise_amplitude": noise,
        "hum_hz": [h for h, _ in hums] + crossing,
    }


def track_errors(scene, result, cpa_seconds=15.0):
    """Measured-ridge error against the generator's received frequency, pooled over events."""
    pooled, near, valid_fraction, cpa_valid, cpa_frames = [], [], [], [], []
    for event, truth, obs in zip(scene["events"], scene["observed_frequency_hz"], result["observations"]):
        times, valid = np.asarray(obs["times"]), np.asarray(obs["valid"])
        index = np.clip(np.rint(times * scene["sample_rate"]).astype(int), 0, len(truth) - 1)
        error = (np.asarray(obs["ridge_hz"]) - truth[index])[valid]
        pooled.extend(error)
        near.extend(error[np.abs(times[valid] - event.cpa) < cpa_seconds])
        valid_fraction.append(float(valid.mean()))
        close = np.abs(times - event.cpa) < cpa_seconds
        cpa_valid.append(int(np.sum(valid & close)))
        cpa_frames.append(int(np.sum(close)))
    pooled, near = np.asarray(pooled), np.asarray(near)
    return {
        "track_rms_hz": float(np.sqrt(np.mean(pooled**2))),
        "track_median_abs_hz": float(np.median(np.abs(pooled))),
        "track_cpa_rms_hz": float(np.sqrt(np.mean(near**2))) if len(near) else None,
        "valid_fraction": valid_fraction,
        "valid_frames": [int(np.sum(o["valid"])) for o in result["observations"]],
        "cpa_valid_frames": cpa_valid,
        "cpa_frames": cpa_frames,
    }


def run_measurement_benchmark(
    seeds=(0, 1, 2),
    scenarios=MEASUREMENT_SCENARIOS + SCENARIOS,
    methods=tuple(MEASUREMENT_METHODS),
    output_dir="outputs/measurement-benchmark",
    window=4.0,
    progress=print,
):
    """STFT ridge versus each measurement option on synthetic waveforms; writes ``results.json``.

    Frequency-track error uses the generator's true received frequency at each
    frame centre and location error the true position; neither enters fitting.
    """
    rows = []
    for scenario in scenarios:
        for seed in seeds:
            scene = audio_scene(int(seed), scenario)
            spec = from_samples(scene["waveform"], scene["sample_rate"], window, 0.5, (40, 450)).whiten()
            audio = Audio(scene["waveform"], scene["sample_rate"])
            candidate = {
                "position": [0.0, 0.0, 0.0],
                "clock": 0.35,
                "f0": [event.f0 for event in scene["events"]],
                "flights": [track.id for track in scene["tracks"]],
            }
            for method in methods:
                started = time.perf_counter()
                row = {"scenario": scenario, "seed": int(seed), "method": method, "error": None}
                try:
                    fit = fit_projected(
                        spec,
                        scene["events"],
                        scene["tracks"],
                        candidate,
                        {**MEASUREMENT_METHODS, **HUM_METHODS}[method],
                        audio=audio,
                        keep_observations=True,
                    )
                    row.update(
                        success=bool(fit["success"]),
                        location_error_m=float(
                            np.linalg.norm(np.asarray(fit["position"])[:2] - scene["truth"][:2])
                        ),
                        event_residual_rms_hz=fit["event_residual_rms_hz"],
                        passes=fit.get("measurement", {}).get("passes", 1),
                        **track_errors(scene, fit),
                    )
                except Exception as exc:  # failures are outcomes, not silently dropped
                    row.update(success=False, error=f"{type(exc).__name__}: {exc}")
                row["seconds"] = time.perf_counter() - started
                rows.append(row)
                if progress:
                    progress(scenario, seed, method, row.get("location_error_m"), row.get("track_rms_hz"))
    summary = {}
    for scenario in scenarios:
        for method in methods:
            chosen = [r for r in rows if r["scenario"] == scenario and r["method"] == method]
            done = [r for r in chosen if r["error"] is None]
            entry = {"failures": len(chosen) - len(done)}
            for key in ("location_error_m", "track_rms_hz", "track_cpa_rms_hz", "track_median_abs_hz"):
                values = [r[key] for r in done if r.get(key) is not None]
                entry[key] = float(np.median(values)) if values else None
            summary[f"{scenario}/{method}"] = entry
    report = {
        "validation": "synthetic waveform measurement benchmark; development seeds only",
        "seeds": [int(s) for s in seeds],
        "window_seconds": window,
        "methods": {name: repr({**MEASUREMENT_METHODS, **HUM_METHODS}[name]) for name in methods},
        "summary_median_over_seeds": summary,
        "trials": rows,
    }
    directory = Path(output_dir)
    directory.mkdir(parents=True, exist_ok=True)
    (directory / "results.json").write_text(json.dumps(report, indent=2, allow_nan=False))
    return report
